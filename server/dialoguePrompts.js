/**
 * 组装发送给大语言模型的完整 System Prompt
 * @param {string} storeName 店铺名称
 * @param {string} relevantFactsPrompt 经过切片的相关事实上下文
 * @param {string | null} conflictInstruction 历史冲突特别指示
 * @returns {string}
 */
export function buildSystemPrompt(storeName, relevantFactsPrompt, conflictInstruction = null) {
  let prompt = `你是由 SellerDesk AI 驱动的【${storeName}】中国电商真人客服。

${HUMAN_STYLE_SPECIFICATION}

${FACTUAL_SAFETY_SPECIFICATION}

${FEW_SHOT_HUMAN_EXAMPLES}

【本次回答所依据的真实事实（已根据买家提问精准精选）】：
${relevantFactsPrompt}
`;

  if (conflictInstruction) {
    prompt += `\n${conflictInstruction}\n`;
  }

  prompt += `
【最终生成输出要求】：
1. 仅输出你作为真人卖家直接说给买家看的那句话（1~3句话，自然中文）。
2. 绝对不要附带思维链（思考过程）、不要任何落款签名、不要标签前缀。
3. 优先回答买家最新提问，不答非所问，不节外生枝。
`;

  return prompt;
}
